"""Write the client protocol in TypeScript, for the desktop app, from `atlas.server.protocol`.

It reads Atlas's standard-library dataclasses (docs/ARCHITECTURE.md, Desktop app):

- Python is the single source: the methods, events and server requests, every shape they carry,
  and the constants a client needs (the subprotocol, the token's prefix, the ready line, the error
  codes).
- `tests/server/test_protocol_generated.py` fails when the committed file differs from what this
  renders, so a shape the server changes fails there before it drifts from the app.
- A field with a default is optional only in a shape the client sends (method params, a server
  request's answer): the server always sends every field (`dump`).
- An unsupported type raises here, so the shape is fixed in Python, never worked around in the
  output.

Run with `uv run python scripts/gen_protocol.py`; `--check` only says whether the file is current.
"""

import dataclasses
import inspect
import json
import re
import sys
import types
from collections.abc import Iterable
from pathlib import Path
from typing import Any, Literal, TypeAliasType, Union, get_args, get_origin, get_type_hints

from atlas.server import (
    EVENTS,
    METHODS,
    PROTOCOL,
    READY_LINE,
    SERVER_REQUESTS,
    TOKEN_PREFIX,
)
from atlas.server import protocol as source

REPOSITORY = Path(__file__).resolve().parents[1]
OUT = REPOSITORY / "apps" / "desktop" / "src" / "protocol" / "protocol.generated.ts"

HEADER = (
    "// GENERATED by scripts/gen_protocol.py from atlas.server.protocol. DO NOT EDIT.\n"
    "// Regenerate: uv run python scripts/gen_protocol.py\n"
    "// tests/server/test_protocol_generated.py fails when this file is stale.\n"
    "/* eslint-disable */\n"
)

#: The error codes a client needs, written in this order.
_ERROR_NAMES = (
    "PARSE_ERROR",
    "INVALID_REQUEST",
    "METHOD_NOT_FOUND",
    "INVALID_PARAMS",
    "INTERNAL_ERROR",
    "NOT_FOUND",
)
_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
_FIELD = re.compile(r"^\s+(\w+)\s*:")


def _ts_literal(value: object) -> str:
    """`value` written in TypeScript; a string in single quotes, the app's prettier style."""
    if not isinstance(value, str):
        return json.dumps(value)
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    return f"'{escaped}'"


def _property_name(name: str) -> str:
    """A bare property name when TypeScript takes it, a quoted one otherwise."""
    if _IDENTIFIER.match(name) is None:
        return _ts_literal(name)
    return name


def _jsdoc(text: str | None, indent: str = "") -> str:
    """A one-line doc comment, whitespace folded; nothing for no text."""
    if not text:
        return ""
    folded = " ".join(text.split())
    return indent + "/** " + folded + " */\n"


def _field_docs(shape: type) -> dict[str, str]:
    """The `#:` comment above each field in the dataclass's source."""
    docs: dict[str, str] = {}
    pending: list[str] = []
    for line in inspect.getsource(shape).splitlines():
        stripped = line.strip()
        if stripped.startswith("#:"):
            pending.append(stripped.removeprefix("#:").strip())
            continue
        match = _FIELD.match(line)
        if match and pending:
            docs[match.group(1)] = " ".join(pending)
        pending = []
    return docs


def _class_doc(shape: type) -> str | None:
    doc = shape.__doc__
    # A dataclass without a docstring gets a generated one: its signature.
    if not doc or doc.startswith(f"{shape.__name__}("):
        return None
    return doc


class Renderer:
    def __init__(self, sent_by_client: set[type]) -> None:
        self.sent_by_client = sent_by_client
        self.emitted: dict[str, str] = {}

    def type_of(self, hint: Any) -> str:
        if isinstance(hint, TypeAliasType):
            hint = hint.__value__
        if hint is object:
            return "unknown"
        origin = get_origin(hint)
        if origin in (Union, types.UnionType):
            return " | ".join(dict.fromkeys(self.type_of(option) for option in get_args(hint)))
        if origin is Literal:
            return " | ".join(_ts_literal(choice) for choice in get_args(hint))
        if origin is list:
            (inner,) = get_args(hint)
            rendered = self.type_of(inner)
            return f"({rendered})[]" if " | " in rendered else f"{rendered}[]"
        if origin is dict:
            key, inner = get_args(hint)
            if key is not str:
                raise TypeError(f"Only string keys reach JSON, not {key!r}.")
            return f"Record<string, {self.type_of(inner)}>"
        if dataclasses.is_dataclass(hint) and isinstance(hint, type):
            self.ensure(hint)
            return hint.__name__
        if hint is type(None):
            return "null"
        if hint is str:
            return "string"
        if hint is bool:
            return "boolean"
        if hint is int or hint is float:
            return "number"
        raise TypeError(f"The protocol cannot carry {hint!r}.")

    def ensure(self, shape: type) -> None:
        name = shape.__name__
        if name in self.emitted:
            return
        self.emitted[name] = ""  # a cycle guard, and the place in the order
        hints = get_type_hints(shape)
        fields = dataclasses.fields(shape)  # pyright: ignore[reportArgumentType]
        docs = _field_docs(shape)
        client = shape in self.sent_by_client
        if not fields:
            body = f"export type {name} = Record<string, never>\n"
        else:
            lines = [f"export interface {name} {{\n"]
            for item in fields:
                has_default = (
                    item.default is not dataclasses.MISSING
                    or item.default_factory is not dataclasses.MISSING
                )
                optional = "?" if client and has_default else ""
                lines.append(_jsdoc(docs.get(item.name), "  "))
                lines.append(
                    f"  {_property_name(item.name)}{optional}: {self.type_of(hints[item.name])}\n"
                )
            lines.append("}\n")
            body = "".join(lines)
        self.emitted[name] = _jsdoc(_class_doc(shape)) + body


def _nested(shapes: Iterable[type]) -> set[type]:
    """The shapes and every dataclass inside them."""
    found: set[type] = set()
    stack = list(shapes)
    while stack:
        shape = stack.pop()
        if shape in found:
            continue
        found.add(shape)
        for hint in get_type_hints(shape).values():
            stack.extend(_dataclasses_in(hint))
    return found


def _dataclasses_in(hint: Any) -> list[type]:
    if isinstance(hint, TypeAliasType):
        hint = hint.__value__
    if dataclasses.is_dataclass(hint) and isinstance(hint, type):
        return [hint]
    return [inner for arg in get_args(hint) for inner in _dataclasses_in(arg)]


def _name_list(constant: str, names: Iterable[str], element: str) -> str:
    """A sorted `as const` array of names, checked against the union `element`."""
    items = ",\n".join(f"  {_ts_literal(name)}" for name in sorted(names))
    return f"export const {constant} = [\n{items}\n] as const satisfies readonly {element}[]\n"


def _keyed_map(interface: str, members: Iterable[tuple[str, str | None, str]]) -> str:
    """An interface with one documented property per (name, doc, type), sorted by name."""
    body = [f"export interface {interface} {{\n"]
    for name, doc, rendered in sorted(members, key=lambda member: member[0]):
        body.append(_jsdoc(doc, "  "))
        body.append(f"  {_property_name(name)}: {rendered}\n")
    body.append("}\n")
    return "".join(body)


def _call(params: type, result: type) -> str:
    return f"{{ params: {params.__name__}; result: {result.__name__} }}"


def _constants() -> str:
    codes = ",\n".join(f"  {name}: {getattr(source, name)}" for name in _ERROR_NAMES)
    return (
        "\n// -- Constants --\n"
        + _jsdoc("The WebSocket subprotocol; the token travels beside it, never in the URL.")
        + f"export const PROTOCOL = {_ts_literal(PROTOCOL)}\n"
        + f"export const TOKEN_PREFIX = {_ts_literal(TOKEN_PREFIX)}\n"
        + _jsdoc("What `atlas serve` writes on standard output, then its port, once it listens")
        + f"export const READY_LINE = {_ts_literal(READY_LINE)}\n"
        + f"export const ERROR_CODES = {{\n{codes}\n}} as const\n"
    )


def _shapes() -> str:
    """Every dataclass the protocol carries, in the order the registries first reach it."""
    sent_by_client = _nested(
        [m.params for m in METHODS.values()] + [r.result for r in SERVER_REQUESTS.values()]
    )
    renderer = Renderer(sent_by_client)
    for method in METHODS.values():
        renderer.ensure(method.params)
        renderer.ensure(method.result)
    for request in SERVER_REQUESTS.values():
        renderer.ensure(request.params)
        renderer.ensure(request.result)
    for event in EVENTS.values():
        renderer.ensure(event.payload)
    return "\n// -- Shapes --\n" + "".join(renderer.emitted.values())


def _methods() -> str:
    members = [(m.name, m.doc, _call(m.params, m.result)) for m in METHODS.values()]
    return (
        "\n// -- Methods (client to server) --\n"
        + _keyed_map("RpcMethods", members)
        + "export type RpcMethod = keyof RpcMethods\n"
        + _name_list("RPC_METHODS", METHODS, "RpcMethod")
    )


def _server_requests() -> str:
    members = [(r.name, r.doc, _call(r.params, r.result)) for r in SERVER_REQUESTS.values()]
    return (
        "\n// -- Server requests (server to client, answered) --\n"
        + _keyed_map("ServerRequestMap", members)
        + "export type ServerRequestMethod = keyof ServerRequestMap\n"
        + _name_list("SERVER_REQUEST_METHODS", SERVER_REQUESTS, "ServerRequestMethod")
    )


def _events() -> str:
    members = [(e.name, e.doc, e.payload.__name__) for e in EVENTS.values()]
    in_conversation = [e.name for e in EVENTS.values() if e.conversation]
    return (
        "\n// -- Events (server to client, `event` notifications) --\n"
        + _keyed_map("EventMap", members)
        + "export type EventName = keyof EventMap\n"
        + _name_list("EVENT_NAMES", EVENTS, "EventName")
        + _jsdoc("Events that belong to a conversation: they carry its id and their number.")
        + _name_list("CONVERSATION_EVENT_NAMES", in_conversation, "EventName")
    )


def render() -> str:
    return HEADER + _constants() + _shapes() + _methods() + _server_requests() + _events()


def main(argv: list[str]) -> int:
    text = render()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    if current == text:
        return 0
    if "--check" in argv:
        sys.stderr.write(f"stale: {OUT.relative_to(REPOSITORY)}; run scripts/gen_protocol.py\n")
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    sys.stdout.write(f"wrote {OUT.relative_to(REPOSITORY)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
